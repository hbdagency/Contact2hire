// Icon component with consistent sizing
interface IconProps {
  name: LucideIcon
  size?: 'sm' | 'md' | 'lg' | 'xl'
  className?: string
}

const sizes = {
  sm: 'w-4 h-4',
  md: 'w-5 h-5',
  lg: 'w-6 h-6',
  xl: 'w-8 h-8',
}

export default function Icon({ name: IconComponent, size = 'md', className = '' }: IconProps) {
  return (
    <IconComponent className={`${sizes[size]} ${className}`} />
  )
}
